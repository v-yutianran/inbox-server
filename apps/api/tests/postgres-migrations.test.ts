import { existsSync, readFileSync, readdirSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";

import { Client } from "pg";
import { afterAll, beforeAll, describe, expect, it } from "vitest";

const d1MigrationFiles = [
  "0001_initial.sql",
  "0002_worker_runtime.sql",
  "0003_queue_inbox.sql",
  "0004_article_retry_safety.sql",
  "0005_operations_readiness.sql",
  "0006_operations_metrics.sql",
  "0007_operations_baselines.sql",
] as const;

function readD1FinalSchema() {
  const database = new DatabaseSync(":memory:");
  for (const filename of d1MigrationFiles) {
    database.exec(
      readFileSync(new URL(`../migrations/${filename}`, import.meta.url), "utf8"),
    );
  }

  const tables = database
    .prepare(
      "SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
    )
    .all() as Array<{ name: string; sql: string }>;

  return { database, tables };
}

describe("PostgreSQL migrations", () => {
  it("matches the 23-table D1 final schema with lossless types and isolated constraints", () => {
    const migrationDirectory = new URL("../postgres-migrations/", import.meta.url);
    const migrationFiles = existsSync(migrationDirectory)
      ? readdirSync(migrationDirectory)
          .filter((filename) => /^\d+.*\.sql$/.test(filename))
          .sort()
      : [];
    expect(migrationFiles).toHaveLength(2);

    const migration = readFileSync(
      new URL(migrationFiles[0]!, migrationDirectory),
      "utf8",
    );
    const { database, tables } = readD1FinalSchema();
    expect(tables).toHaveLength(23);
    expect(migration).toMatch(/CREATE SCHEMA IF NOT EXISTS inbox_server/i);
    expect(migration).not.toMatch(/\bpublic\s*\./i);

    for (const { name, sql } of tables) {
      const tableMatch = migration.match(
        new RegExp(
          `CREATE TABLE IF NOT EXISTS inbox_server\\.${name}\\s*\\(([\\s\\S]*?)\\n\\);`,
          "i",
        ),
      );
      expect(tableMatch, `missing isolated table ${name}`).toBeTruthy();
      expect(tableMatch![1]!.match(/\bCHECK\s*\(/gi) ?? [], `${name} checks`).toHaveLength(
        sql.match(/\bCHECK\s*\(/gi)?.length ?? 0,
      );
      const sqliteColumns = database
        .prepare(`PRAGMA table_info("${name}")`)
        .all() as Array<{
        name: string;
        notnull: number;
        pk: number;
        type: string;
      }>;
      expect(
        [...tableMatch![1]!.matchAll(/^ {2}([a-z_]+)\s+(?:BIGINT|BYTEA|DOUBLE PRECISION|TEXT)\b/gim)]
          .map((match) => match[1])
          .sort(),
        `${name} exact columns`,
      ).toEqual(sqliteColumns.map(({ name: column }) => column).sort());
      for (const { name: column, notnull, type, pk } of sqliteColumns) {
        const postgresType = {
          BLOB: "BYTEA",
          INTEGER: "BIGINT",
          REAL: "DOUBLE PRECISION",
          TEXT: "TEXT",
        }[type.toUpperCase()];
        expect(postgresType, `${name}.${column} source type ${type}`).toBeDefined();
        const columnDefinition = tableMatch![1]!
          .split("\n")
          .find((line) => new RegExp(`^\\s*${column}\\s`, "i").test(line));
        expect(columnDefinition, `${name}.${column} definition`).toMatch(
          new RegExp(`^\\s*${column}\\s+${postgresType}\\b`, "i"),
        );
        if (pk === 1 && sqliteColumns.filter(({ pk: key }) => key > 0).length === 1) {
          expect(columnDefinition).toMatch(/PRIMARY KEY/i);
        }
        if (/AUTOINCREMENT/i.test(sql) && pk === 1) {
          expect(columnDefinition).toMatch(/GENERATED BY DEFAULT AS IDENTITY/i);
        }
        if (notnull === 1) {
          expect(columnDefinition).toMatch(/NOT NULL/i);
        }
      }

      const uniqueConstraints = database
        .prepare(`PRAGMA index_list("${name}")`)
        .all() as Array<{ name: string; origin: string; unique: number }>;
      for (const { name: indexName, origin, unique } of uniqueConstraints) {
        if (unique !== 1 || origin !== "u") continue;
        const columns = database
          .prepare(`PRAGMA index_info("${indexName}")`)
          .all() as Array<{ name: string }>;
        if (columns.length === 1) {
          const columnDefinition = tableMatch![1]!
            .split("\n")
            .find((line) => new RegExp(`^\\s*${columns[0]!.name}\\s`, "i").test(line));
          expect(columnDefinition, `${name}.${columns[0]!.name} unique`).toMatch(/\bUNIQUE\b/i);
        } else {
          expect(tableMatch![1]).toMatch(
            new RegExp(`UNIQUE \\(${columns.map(({ name: column }) => column).join(", ")}\\)`, "i"),
          );
        }
      }

      const primaryKeyColumns = sqliteColumns
        .filter(({ pk }) => pk > 0)
        .sort((left, right) => left.pk - right.pk)
        .map(({ name: column }) => column);
      if (primaryKeyColumns.length > 1) {
        expect(tableMatch![1]).toMatch(
          new RegExp(`PRIMARY KEY \\(${primaryKeyColumns.join(", ")}\\)`, "i"),
        );
      }
    }

    expect(migration).toMatch(/CREATE TABLE IF NOT EXISTS inbox_server\.worker_inbox[\s\S]*?timestamp_ms BIGINT/i);
    expect(migration).toMatch(/CREATE UNIQUE INDEX IF NOT EXISTS worker_inbox_lease_id_uq\s+ON inbox_server\.worker_inbox[\s\S]*?WHERE lease_id IS NOT NULL/i);
    expect(migration).toMatch(/CREATE UNIQUE INDEX IF NOT EXISTS article_archive_events_import_idx\s+ON inbox_server\.article_archive_events\s*\(url_fingerprint, status, occurred_at\)/i);
    expect(migration).toMatch(/CREATE TABLE IF NOT EXISTS inbox_server\.worker_jobs[\s\S]*?status IN \('processing', 'deferred', 'done', 'failed', 'dead', 'uncertain'\)/i);
    expect(migration).toMatch(/CREATE TABLE IF NOT EXISTS inbox_server\.worker_effects[\s\S]*?status IN \('processing', 'done', 'failed', 'uncertain'\)/i);
    expect(migration).toMatch(/CREATE TABLE IF NOT EXISTS inbox_server\.operations_snapshots[\s\S]*?id = 'current'/i);
    expect(migration).toMatch(
      /CREATE TABLE IF NOT EXISTS inbox_server\.schema_migrations\s*\(\s*version TEXT PRIMARY KEY,\s*applied_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp\(\)/i,
    );
    expect(migration).toMatch(
      /INSERT INTO inbox_server\.schema_migrations\s*\(version\)\s*VALUES\s*\('0001_initial'\)\s*ON CONFLICT \(version\) DO NOTHING/i,
    );

    const sqliteIndexes = database
      .prepare(
        "SELECT name, tbl_name, sql FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL ORDER BY name",
      )
      .all() as Array<{ name: string; tbl_name: string; sql: string }>;
    for (const { name, tbl_name, sql } of sqliteIndexes) {
      const unique = /\bCREATE UNIQUE INDEX\b/i.test(sql);
      const indexMatch = migration.match(
        new RegExp(
          `CREATE ${unique ? "UNIQUE " : ""}INDEX IF NOT EXISTS ${name}\\s+ON inbox_server\\.${tbl_name}\\s*\\(([^)]*)\\)(?:\\s+WHERE\\s+([^;]+))?;`,
          "i",
        ),
      );
      expect(indexMatch, `missing PostgreSQL index ${name} on ${tbl_name}`).toBeTruthy();
      const sourceColumns = sql.match(/\(([^)]*)\)/)?.[1]?.replace(/\s+/g, " ").trim();
      expect(indexMatch![1]!.replace(/\s+/g, " ").trim()).toBe(sourceColumns);
      const sourcePredicate = sql.match(/\bWHERE\s+([^;]+)/i)?.[1]?.trim();
      expect(indexMatch![2]?.trim()).toBe(sourcePredicate);
    }

    expect(migration.match(/CREATE TABLE IF NOT EXISTS/gi)).toHaveLength(24);
    expect(migration).not.toMatch(/CREATE (?:UNIQUE )?INDEX\s+(?!IF NOT EXISTS)/i);
    expect(migration).not.toMatch(/CREATE TABLE\s+(?!IF NOT EXISTS)/i);

    const legacyArchiveMigration = readFileSync(
      new URL("0002_legacy_archive.sql", migrationDirectory),
      "utf8",
    );
    expect(legacyArchiveMigration).toMatch(/CREATE SCHEMA IF NOT EXISTS inbox_server_legacy/i);
    expect(legacyArchiveMigration).toMatch(
      /CREATE TABLE IF NOT EXISTS inbox_server_legacy\.volume_archives/i,
    );
    expect(legacyArchiveMigration).toMatch(/archive_bytes BYTEA NOT NULL/i);
    expect(legacyArchiveMigration).toMatch(/octet_length\(archive_bytes\) = byte_length/i);
    expect(legacyArchiveMigration).toMatch(
      /INSERT INTO inbox_server\.schema_migrations\s*\(version\)\s*VALUES\s*\('0002_legacy_archive'\)\s*ON CONFLICT \(version\) DO NOTHING/i,
    );
  });
});

const rawDatabaseUrl = process.env.INBOX_TEST_POSTGRES_URL;
const databaseUrl = rawDatabaseUrl ? localTestDatabaseUrl(rawDatabaseUrl) : undefined;
const integration = databaseUrl ? describe : describe.skip;

integration("PostgreSQL 17.6 schema migration integration", () => {
  let client: Client | undefined;

  beforeAll(async () => {
    client = new Client({ connectionString: databaseUrl });
    await client.connect();
    const version = await client.query<{ version_num: number }>(
      "SELECT current_setting('server_version_num')::int AS version_num",
    );
    if (version.rows[0]?.version_num !== 170006) {
      throw new Error("INBOX_TEST_POSTGRES_URL must point to PostgreSQL 17.6");
    }
  });

  afterAll(async () => {
    await client?.end();
  });

  it("records the initial version once and keeps the 23 business tables on repeat", async () => {
    const migration = readFileSync(
      new URL("../postgres-migrations/0001_initial.sql", import.meta.url),
      "utf8",
    );
    await client!.query(migration);
    const migration2 = readFileSync(
      new URL("../postgres-migrations/0002_legacy_archive.sql", import.meta.url),
      "utf8",
    );
    await client!.query(migration2);
    const first = await client!.query<{ version: string; applied_at: string }>(
      "SELECT version, applied_at FROM inbox_server.schema_migrations ORDER BY version",
    );
    expect(first.rows).toEqual([
      expect.objectContaining({ version: "0001_initial", applied_at: expect.any(Date) }),
      expect.objectContaining({ version: "0002_legacy_archive", applied_at: expect.any(Date) }),
    ]);

    await client!.query(migration);
    await client!.query(migration2);
    const repeated = await client!.query<{ version: string; applied_at: string }>(
      "SELECT version, applied_at FROM inbox_server.schema_migrations ORDER BY version",
    );
    const tables = await client!.query<{ count: string }>(
      "SELECT count(*)::text AS count FROM information_schema.tables " +
        "WHERE table_schema = 'inbox_server' AND table_type = 'BASE TABLE' " +
        "AND table_name <> 'schema_migrations'",
    );
    const archiveTables = await client!.query<{ count: string }>(
      "SELECT count(*)::text AS count FROM information_schema.tables " +
        "WHERE table_schema = 'inbox_server_legacy' AND table_type = 'BASE TABLE'",
    );

    expect(repeated.rows).toEqual(first.rows);
    expect(tables.rows[0]?.count).toBe("23");
    expect(archiveTables.rows[0]?.count).toBe("1");
  });
});

function localTestDatabaseUrl(value: string): string {
  let parsed: URL;
  try {
    parsed = new URL(value);
  } catch {
    throw new Error("INBOX_TEST_POSTGRES_URL must be a PostgreSQL URL for a local test database");
  }
  const hostname = parsed.hostname.replace(/^\[|\]$/g, "").toLowerCase();
  const database = decodeURIComponent(parsed.pathname.slice(1));
  const isLocal = ["localhost", "127.0.0.1", "::1"].includes(hostname);
  const isTestDatabase = /(?:^|[_-])test(?:$|[_-])/i.test(database);
  if (!/^postgres(?:ql)?:$/.test(parsed.protocol) || !isLocal || !isTestDatabase) {
    throw new Error("INBOX_TEST_POSTGRES_URL must use a local *_test database; remote databases are refused");
  }
  return value;
}
